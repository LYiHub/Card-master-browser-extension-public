import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';
import sharp from 'sharp';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const cardArtRoot = resolve(root, 'assets/userscript-deck/card-art');

export const CARD_MEDIA_ACCENT_OUTPUT = resolve(
  root,
  'src/generated/card-media-accents.generated.ts',
);

async function filesRecursively(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const path = resolve(directory, entry.name);
      return entry.isDirectory() ? filesRecursively(path) : [path];
    }),
  );
  return files.flat();
}

async function accentDeriver() {
  const result = await build({
    entryPoints: [resolve(root, 'src/userscript/application/card-accent.ts')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    write: false,
  });
  const source = result.outputFiles[0]?.text;
  if (!source) throw new Error('无法加载卡牌封面取色算法。');
  const module = await import(
    `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`
  );
  if (typeof module.deriveCardAccent !== 'function') {
    throw new Error('卡牌封面取色算法没有导出 deriveCardAccent。');
  }
  return module.deriveCardAccent;
}

function assetPath(path) {
  return relative(resolve(root, 'assets'), path).split(sep).join('/');
}

function generatedSource(accents) {
  const entries = Object.entries(accents)
    .map(([poster, accent]) => {
      const entry = `  '${poster}': '${accent}',`;
      return entry.length <= 80 ? entry : `  '${poster}':\n    '${accent}',`;
    })
    .join('\n');
  return `// Generated by scripts/generate-card-media-accents.mjs. Do not edit.
import { DEFAULT_CARD_ACCENT } from '../userscript/application/card-accent';

export const CARD_MEDIA_ACCENTS = {
${entries}
} as const satisfies Readonly<Record<string, string>>;

export function cardMediaAccent(poster: string) {
  return (
    CARD_MEDIA_ACCENTS[poster as keyof typeof CARD_MEDIA_ACCENTS] ??
    DEFAULT_CARD_ACCENT
  );
}
`;
}

export async function buildCardMediaAccentCatalog() {
  const deriveCardAccent = await accentDeriver();
  const posters = (await filesRecursively(cardArtRoot))
    .filter((path) => path.endsWith('.webp'))
    .sort();
  const accents = {};
  for (const poster of posters) {
    const { data, info } = await sharp(poster)
      .resize(48, 64, { fit: 'fill', kernel: sharp.kernel.lanczos3 })
      .ensureAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    accents[assetPath(poster)] = deriveCardAccent(
      data,
      info.width,
      info.height,
    );
  }
  return {
    accents,
    source: generatedSource(accents),
  };
}

export async function writeCardMediaAccentCatalog() {
  const generated = await buildCardMediaAccentCatalog();
  const current = await readFile(CARD_MEDIA_ACCENT_OUTPUT, 'utf8').catch(
    () => null,
  );
  if (current === generated.source) return false;
  await mkdir(dirname(CARD_MEDIA_ACCENT_OUTPUT), { recursive: true });
  await writeFile(CARD_MEDIA_ACCENT_OUTPUT, generated.source);
  return true;
}
